// Demonstrates fundamental variable types and printing their values.


#include<iostream>

using namespace std;

int main()
{
    int a = 6;
    int b = 8;
    float pi = 3.14;
    char c = 's';
    bool t = true;

    cout <<"The value of a is : " << a; 
    cout <<"\nThe value of b is : " << b;
    cout <<"\nThe value of pi is : " << pi;
    cout <<"\nThe value of c is : " << c;
    cout <<"\nThe value of t is : " << t;
    
    return 0;
}
