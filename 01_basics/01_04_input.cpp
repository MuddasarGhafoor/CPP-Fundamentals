// Reads two integers from standard input and prints their sum.


#include<iostream>

using namespace std;

int main()
{
    int num_1;
    int num_2;

    cout << "Enter the value of first number : ";
    cin >> num_1;

    cout << "Enter the value of second number : ";
    cin >> num_2;

    cout << "The sum of first and second number is : " << num_1 + num_2;
    
    return 0;
}
